import json
from pathlib import Path
from e2ebench.benchmark import to_markdown, to_json
p=Path('.')
r=json.loads((p/'out/report.json').read_text())
expected={'careful':(8,1.0,0.0,0,0.0,59,59,1.0,1.0),'sloppy':(1,.125,.875,1,.25,24,36,.6667,.6102)}
for name,e in expected.items():
 m=r['verifiers'][name]['metrics']
 actual=(m['defects_detected'],m['defect_detection_rate'],m['false_pass_rate'],m['false_fail_apps'],m['false_fail_rate'],m['traceable_verdicts'],m['verdicts_total'],m['traceability_rate'],m['check_level']['coverage'])
 assert actual==e,(name,actual,e)
 print(name,json.dumps(m,sort_keys=True))
provenance='Generated by running the benchmark: python demo.py --out out (Python 3.13.13).'
(p/'sample_report/report.md').write_text(to_markdown(r,banner=provenance))
(p/'sample_report/report.json').write_text(to_json(r,extra={'generation_note':provenance}))
f=p/'README.md'
s=f.read_text().replace('The 12 apps, their defects and all results are\n  invented.', 'The 12 apps and their defects are invented; results are measured\n  by executing the synthetic benchmark.')
s=s.replace('- `sample_report/` is **hand-derived**, not produced by running code (the\n  build environment had no code execution). Run `python demo.py` to get real\n  output, and `python -m unittest discover -s tests -t .` for the tests.', '- `sample_report/` was generated by running the benchmark with Python 3.13.13.\n  Verification: all 32 tests passed. Run `python demo.py --out out` to reproduce\n  output, and `python -m unittest discover -s tests -t .` for the tests.')
f.write_text(s)
